# CHARTS -------------------------------------------------------------
# ==========================================================================
def charts(survey):
    # Chart 1: concern vs action scatter, colored by migrant status
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.scatterplot(data=survey, x="concern", y="action_score",
                    hue="is_migrant", palette={0: "#2e7d32", 1: "#c0392b"},
                    s=90, alpha=0.85, ax=ax)
    ax.set_title("Concern vs actual pro-environmental action (35 Delhi students)")
    ax.set_xlabel("Concern score (1–5)"); ax.set_ylabel("Action score (0–5)")
    h, l = ax.get_legend_handles_labels()
    ax.legend(h, ["Delhi natives", "Migrants (other states)"], title="")
    fig.tight_layout(); fig.savefig(f"{OUT}/fig1_concern_vs_action.png", dpi=130); plt.close(fig)

    # Chart 2: intention-behaviour gap per respondent
    fig, ax = plt.subplots(figsize=(9, 5))
    survey_sorted = survey.sort_values("gap")
    colors = ["#c0392b" if g > 1 else ("#f39c12" if g > 0 else "#2e7d32")
              for g in survey_sorted["gap"]]
    ax.bar(survey_sorted["respondent_id"], survey_sorted["gap"], color=colors)
    ax.axhline(0, color="k", lw=1)
    ax.set_title("Intention–behaviour gap (>0 = says they care but act less)")
    ax.set_xlabel("Respondent"); ax.set_ylabel("Gap (intention − action)")
    plt.xticks(rotation=90, fontsize=6)
    fig.tight_layout(); fig.savefig(f"{OUT}/fig2_intention_gap.png", dpi=130); plt.close(fig)

    # Chart 3: concern vs home-state PM2.5 (migrants only) + trend line
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.regplot(data=survey, x="state_pm25", y="concern",
                scatter_kws={"s": 70, "alpha": 0.8}, ax=ax, color="#2e7d32")
    ax.set_title("Home-state air pollution vs environmental concern")
    ax.set_xlabel("Home-state annual mean PM2.5 (µg/m³) — indicative")
    ax.set_ylabel("Concern score (1–5)")
    fig.tight_layout(); fig.savefig(f"{OUT}/fig3_pollution_vs_concern.png", dpi=130); plt.close(fig)


def main():
    layerA_df = layerA()

"""
FULL PROJECT PIPELINE
=====================
"Understanding Pro-Environmental Behaviour Among the Youth" — Delhi study

Layer A (OPEN SOURCE / public data): real pollution & emissions data from the
   free World Bank API (no key needed). Plus an indicative state-level PM2.5
   lookup used to assign each respondent's "home-environment" pollution.

Layer B (SURVEY): 35 Delhi students (20 Delhi natives + 15 from other states),
   generated by generate_survey.py (replace with your real Google Form export).

The pipeline:
   1. Pull Layer A (World Bank) -> charts of pollution context.
   2. Load Layer B (survey), compute concern / intention / action / gap.
   3. JOIN the two layers (per-respondent home-state PM2.5).
   4. Statistics: group means, t-test (migrant vs native), correlation,
      simple regression (action ~ concern + intention + pollution).
   5. Save figures + a results table.

Run:  python3 analysis.py
"""


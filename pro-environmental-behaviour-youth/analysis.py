# ==========================================================================
# JOIN + STATISTICS --------------------------------------------------------
# ==========================================================================
def analyse(survey):
    print("\n[Analysis] Joining layers and testing hypotheses...")
    # per-respondent home-environment pollution is already in survey (state_pm25)

    # 1) Group comparison: Delhi natives vs migrants from other states
    groups = {}
    for mig, label in [(0, "Delhi natives (n=20)"), (1, "Migrants from other states (n=15)")]:
        g = survey[survey.is_migrant == mig]
        groups[label] = {
            "n": len(g),
            "concern": g["concern"].mean(),
            "intention": g["intention"].mean(),
            "action": g["action_score"].mean(),
            "gap": g["gap"].mean(),
        }
    grp = pd.DataFrame(groups).T.round(2)
    grp.to_csv(f"{OUT}/results_group_means.csv")
    print(grp)

    # 2) t-test: migrant vs native on concern and action
    tt = {}
    for col in ["concern", "intention", "action_score", "gap"]:
        a = survey[survey.is_migrant == 0][col]
        b = survey[survey.is_migrant == 1][col]
        t, p = stats.ttest_ind(a, b, equal_var=False)
        tt[col] = {"t": round(t, 3), "p": round(p, 3),
                   "sig_05": "yes" if p < 0.05 else "no"}
    ttest = pd.DataFrame(tt).T
    ttest.to_csv(f"{OUT}/results_ttest.csv")
    print("\n=== t-test (migrant vs native) ===")
    print(ttest)

    # 3) Correlation: concern ~ action ; intention ~ action ; pollution ~ concern
    corr = {}
    for x, y in [("concern", "action_score"), ("intention", "action_score"),
                 ("state_pm25", "concern"), ("state_pm25", "action_score")]:
        r, p = stats.pearsonr(survey[x], survey[y])
        corr[f"{x} vs {y}"] = {"r": round(r, 3), "p": round(p, 3)}
    corrdf = pd.DataFrame(corr).T
    corrdf.to_csv(f"{OUT}/results_correlations.csv")
    print("\n=== Correlations ===")
    print(corrdf)

    # 4) Regression: action ~ concern + intention + home-state PM2.5
    X = np.column_stack([np.ones(len(survey)), survey["concern"],
                         survey["intention"], survey["state_pm25"]])
    y = survey["action_score"].values.astype(float)
    # handle the NA-features: use intention & concern (all present)
    X = np.column_stack([np.ones(len(survey)), survey["concern"], survey["intention"]])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    yhat = X @ beta
    ss_res = np.sum((y - yhat) ** 2); ss_tot = np.sum((y - y.mean()) ** 2)
    r2 = 1 - ss_res / ss_tot
    reg = pd.DataFrame({"coef_Intercept": beta[0], "coef_concern": beta[1],
                        "coef_intention": beta[2], "R2": r2}, index=[0]).round(3)
    reg.to_csv(f"{OUT}/results_regression.csv")
    print("\n=== Simple regression (action ~ concern + intention) ===")
    print(reg)

    return survey, grp



# ==========================================================================
# LAYER A  -- OPEN-SOURCE PUBLIC DATA (World Bank, no key) ----------------
# ==========================================================================
def worldbank(indicator, country="IN", start=1990, end=2024):
    url = (f"https://api.worldbank.org/v2/country/{country}/indicator/{indicator}"
           f"?format=json&per_page=200&date={start}:{end}")
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.loads(r.read().decode())
    if not isinstance(data, list) or len(data) < 2:
        return pd.Series(dtype=float)
    out = {int(e["date"]): e["value"] for e in (data[1] or []) if e.get("value") is not None}
    return pd.Series(out, dtype=float)


def layerA():
    print("[Layer A] Pulling real World Bank open data for India...")
    ind = {  # live indicator codes (verified 2026)
        "pm25":      "EN.ATM.PM25.MC.M3",
        "co2_pc":    "EN.GHG.CO2.PC.CE.AR5",
        "forest":    "AG.LND.FRST.ZS",
        "gdp_pc":    "NY.GDP.PCAP.CD",
        "pop":       "SP.POP.TOTL",
    }
    ser = {k: worldbank(v) for k, v in ind.items()}
    df = pd.DataFrame(ser).sort_index()
    df = df[df.index <= 2024]
    os.makedirs("data", exist_ok=True)
    df.to_csv("data/data_layerA_india.csv")
    print(f"   -> India {len(df)} years (1990-{int(df.index.max())})")

    # Chart 1: India PM2.5 + CO2 per capita over time
    fig, ax1 = plt.subplots(figsize=(9, 5))
    ax1.plot(df.index, df["pm25"], color="#c0392b", marker="o", ms=3, label="PM2.5 (µg/m³)")
    ax1.set_ylabel("PM2.5 mean exposure (µg/m³)", color="#c0392b")
    ax1.tick_params(axis="y", colors="#c0392b")
    ax2 = ax1.twinx()
    ax2.plot(df.index, df["co2_pc"], color="#2e7d32", marker="s", ms=3, label="CO₂/capita (t)")
    ax2.set_ylabel("CO₂ per capita (t CO₂e)", color="#2e7d32")
    ax2.tick_params(axis="y", colors="#2e7d32")
    ax1.set_title("India: ambient PM2.5 vs per-capita CO₂ (World Bank / open data)")
    ax1.set_xlabel("Year")
    fig.tight_layout(); fig.savefig(f"{OUT}/fig_A_india_trends.png", dpi=130); plt.close(fig)
    return df


